// One-time generator for src/lib/microsites/account-domains.ts (S1 amplifier).
// For every microsite registry account, find the CANONICAL HubSpot company
// (name-token search, most associated contacts wins) and emit its DOMAIN — the
// value that will actually match at intent-stamp time. The map must mirror
// HubSpot's own domain values, not "true" corporate domains, or domain-first
// resolution just trades one silent miss for another.
// Output: a review table (stderr) + the map file body (stdout). Read-only.
// Usage: node scripts/tam/gen-account-domains.mjs > /tmp/account-domains.txt
import { readFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const env = readFileSync(join(ROOT, '.env.local'), 'utf8');
const TOKEN = (env.match(/HUBSPOT_ACCESS_TOKEN\s*=\s*"?([^"\n\r]+)"?/) || [])[1];
const H = { Authorization: `Bearer ${TOKEN}`, 'Content-Type': 'application/json' };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// Extract slug + accountName from each registry pack (uniform literal fields).
const dir = join(ROOT, 'src/lib/microsites/accounts');
const accounts = [];
for (const f of readdirSync(dir).filter((f) => f.endsWith('.ts'))) {
  const src = readFileSync(join(dir, f), 'utf8');
  const slug = (src.match(/slug:\s*'([^']+)'/) || [])[1];
  const name = (src.match(/accountName:\s*'([^']+)'/) || [])[1];
  if (slug && name) accounts.push({ slug, name, file: f });
  else console.error(`SKIP ${f}: no slug/accountName literal`);
}
console.error(`registry accounts: ${accounts.length}`);

async function search(value) {
  const res = await fetch('https://api.hubapi.com/crm/v3/objects/companies/search', {
    method: 'POST', headers: H,
    body: JSON.stringify({
      filterGroups: [{ filters: [{ propertyName: 'name', operator: 'CONTAINS_TOKEN', value }] }],
      properties: ['name', 'domain', 'num_associated_contacts', 'yardflow_tam'],
      sorts: [{ propertyName: 'num_associated_contacts', direction: 'DESCENDING' }],
      limit: 5,
    }),
  });
  if (!res.ok) { console.error(`  search ${res.status} for "${value}"`); return []; }
  return (await res.json()).results ?? [];
}

const rows = [];
for (const a of accounts) {
  let results = await search(a.name);
  if (!results.length && a.name.includes(' ')) results = await search(a.name.split(' ')[0]);
  await sleep(150);
  const top = results[0]?.properties;
  const contacts = parseInt(top?.num_associated_contacts || '0', 10) || 0;
  const domain = (top?.domain || '').toLowerCase().trim();
  // Confidence: canonical when the top hit has a domain, has contacts, and its
  // name shares the account's first token (case-insensitive).
  const tok = a.name.split(' ')[0].toLowerCase();
  const nameOk = (top?.name || '').toLowerCase().includes(tok);
  const conf = domain && nameOk ? (contacts > 0 ? 'HIGH' : 'MED') : 'LOW';
  rows.push({ ...a, domain, hsName: top?.name || '(none)', contacts, tam: top?.yardflow_tam || '', conf,
    alts: results.slice(1, 3).map((r) => `${r.properties.name}|${r.properties.domain || '-'}|${r.properties.num_associated_contacts || 0}`) });
  console.error(`${a.slug.padEnd(28)} ${conf.padEnd(4)} ${domain.padEnd(30)} <- "${top?.name || '(none)'}" (${contacts} contacts, tam=${top?.yardflow_tam || '-'})`);
}

// stdout: the map body for account-domains.ts, sorted, LOW-confidence commented out.
console.log('// GENERATED by scripts/tam/gen-account-domains.mjs — review before commit');
for (const r of rows.sort((x, y) => x.slug.localeCompare(y.slug))) {
  const line = `  '${r.slug}': '${r.domain}',`;
  if (r.conf === 'LOW' || !r.domain) console.log(`  // UNRESOLVED ${r.slug} (hs: ${r.hsName}) alts: ${r.alts.join(' / ') || 'none'}`);
  else console.log(`${line} // ${r.hsName}, ${r.contacts} contacts${r.conf === 'MED' ? ' [MED - review]' : ''}`);
}
